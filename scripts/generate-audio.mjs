// Records the English lesson audio with Azure's natural US English voice
// (en-US-AvaNeural), a little slower than normal for a beginner. "Mai rar"
// plays these same recordings at a slower speed.
// Also records the real-speed shop dialogues: store staff with a Canadian
// voice, the customer with the usual voice, at normal speaking speed.
//   npm run generate-audio
// Needs the Azure settings described in scripts/audio-tools.mjs.
import { writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';

import {
  dialogueAudioSources,
  generatedEnglishAudioSources,
} from '../src/data/audio/english-audio-catalog.ts';
import {
  ENGLISH_VOICE,
  NATURAL_RATE,
  STAFF_VOICES,
  ensureSpeech,
  groupByText,
  joinAudio,
  projectRoot,
  removeStaleFiles,
  speechPath,
} from './audio-tools.mjs';

const audioDirectory = join(projectRoot, 'assets', 'audio', 'en-US');
const dialogueDirectory = join(audioDirectory, 'dialogue');
const assetMapPath = join(projectRoot, 'src', 'data', 'audio', 'generated-audio-assets.ts');

const keys = new Set();
for (const source of [...generatedEnglishAudioSources, ...dialogueAudioSources]) {
  if (!/^[a-z0-9-]+$/.test(source.key)) {
    throw new Error(`Unsafe audio key: ${source.key}`);
  }
  if (keys.has(source.key)) {
    throw new Error(`Duplicate audio key: ${source.key}`);
  }
  keys.add(source.key);
}

const phrases = groupByText(generatedEnglishAudioSources, audioDirectory);
const dialogues = dialogueAudioSources.map((dialogue) => ({
  key: dialogue.key,
  output: join(dialogueDirectory, `${dialogue.key}.mp3`),
  lines: dialogue.lines.map((line) => ({
    voice: line.speaker === 'staff' ? STAFF_VOICES[dialogue.staffVoice] : ENGLISH_VOICE,
    text: line.english,
    rate: NATURAL_RATE,
  })),
}));

await ensureSpeech([
  ...phrases.map(({ text }) => ({ voice: ENGLISH_VOICE, text })),
  ...dialogues.flatMap(({ lines }) => lines),
]);

console.log(`Saving ${phrases.length} English recordings and ${dialogues.length} dialogues...`);
await joinAudio([
  ...phrases.map(({ text, output }) => ({
    output,
    parts: [{ silence: 0.1 }, { wav: speechPath(ENGLISH_VOICE, text) }, { silence: 0.3 }],
  })),
  ...dialogues.map(({ output, lines }) => ({
    output,
    parts: [
      { silence: 0.1 },
      ...lines.flatMap((line, index) => [
        ...(index > 0 ? [{ silence: 0.6 }] : []),
        { wav: speechPath(line.voice, line.text, line.rate) },
      ]),
      { silence: 0.3 },
    ],
  })),
]);
// Also removes recordings that no longer belong to any lesson.
await removeStaleFiles(
  audioDirectory,
  phrases.map(({ output }) => output),
);
await removeStaleFiles(
  dialogueDirectory,
  dialogues.map(({ output }) => output),
);

const importPathOf = (output) => relative(dirname(assetMapPath), output).replaceAll('\\', '/');
const entries = [
  ...phrases.flatMap(({ output, keys: phraseKeys }) =>
    phraseKeys.map((key) => `  '${key}': require('${importPathOf(output)}'),`),
  ),
  ...dialogues.map(({ key, output }) => `  '${key}': require('${importPathOf(output)}'),`),
];
await writeFile(
  assetMapPath,
  [
    '// Generated by `npm run generate-audio`. Do not edit this file manually.',
    'export const generatedAudioAssets: Readonly<Record<string, number>> = {',
    ...entries,
    '};',
    '',
  ].join('\n'),
  'utf8',
);
console.log(
  `\nDone: ${phrases.length} recordings and ${dialogues.length} dialogues for ${entries.length} audio keys.`,
);
